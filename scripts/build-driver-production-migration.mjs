import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = new URL("../", import.meta.url);
function replaceOnce(sql, before, after) {
  if (sql.split(before).length !== 2) throw new Error(`Unexpected migration source: ${before}`);
  return sql.replace(before, after);
}

export function buildDriverProductionMigration() {
  const directory = new URL("supabase/driver-pwa-test/", root);
  const sources = readdirSync(directory).filter(name =>
    /^\d{3}-.*\.sql$/.test(name) && !/-(test|verify|rollback)\.sql$/.test(name) &&
    !name.startsWith("001-") && !name.startsWith("004-"),
  ).sort();
  if (sources.length !== 29) throw new Error("Unexpected driver migration inventory.");
  const prefix = readFileSync(new URL("supabase/driver-production/prepare.sql", root), "utf8");
  const suffix = readFileSync(new URL("supabase/driver-production/dispatch.sql", root), "utf8");
  const parts = sources.map(name => {
    let sql = readFileSync(new URL(name, directory), "utf8").replace(/\r\n/g, "\n");
    const digest = createHash("sha256").update(sql).digest("hex");
    sql = sql.replace(/^--[^\n]*\n/, "").replace(/^begin;\n/m, "").replace(/commit;\s*$/, "");
    if (name.startsWith("002-")) {
      sql = replaceOnce(sql, `  if (select count(*) from public.profiles) <> 2 then
    raise exception 'Expected the two inspected legacy staff profiles';
  end if;
`, "");
      sql = replaceOnce(sql, "'vehicle_monthly_finances', 'balance_expense_items'",
        "'vehicle_monthly_finances', 'balance_expense_items', 'driver_wage_items', 'invoice_counters', 'invoice_numbers'");
    }
    if (name.startsWith("019-")) {
      const start = sql.indexOf("-- Test project did not yet contain");
      const end = sql.indexOf("create table public.driver_finance_claims");
      if (start < 0 || end <= start) throw new Error("Unexpected payroll expansion source.");
      sql = sql.slice(0, start) + sql.slice(end);
    }
    return `-- Source: ${name}; SHA256: ${digest}\n${sql}`;
  });
  return [
    "-- Generated by scripts/build-driver-production-migration.mjs; do not apply test/demo SQL directly.",
    "begin;\nset local lock_timeout='3s';\nset local statement_timeout='60s';",
    prefix, ...parts, suffix, "commit;\n",
  ].join("\n\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const destination = process.argv[2];
  if (!destination) throw new Error("Provide an explicit output file path; no migration is executed.");
  writeFileSync(destination, buildDriverProductionMigration());
  console.log("Generated driver production migration. No database was changed.");
}
